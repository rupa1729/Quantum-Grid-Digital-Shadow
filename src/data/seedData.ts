function makeNode(
  id: string,
  name: string,
  role: GridNode['role'],
  region: string,
  x: number,
  y: number,
  loadMW: number,
  capacityMW: number,
  voltagePU: number,
  temperatureC: number,
  phaseAngleDeg: number,
  qubitIndex: number
): GridNode {
  return {
    id,
    name,
    role,
    region,
    x,
    y,
    loadMW,
    capacityMW,
    voltagePU,
    temperatureC,
    phaseAngleDeg,
    qubitIndex,
    status: computeNodeStatus(loadMW, capacityMW, voltagePU, temperatureC),
    quantumDispatchMW: roundTo(loadMW * 0.87, 1),
    classicalDispatchMW: roundTo(loadMW * 1.02, 1),
  };
}

function makeEdge(
  id: string,
  source: string,
  target: string,
  flowMW: number,
  limitMW: number,
  resistanceOhm: number,
  isQuantumPath: boolean,
  isClassicalPath: boolean
): GridEdge {
  return {
    id,
    source,
    target,
    flowMW,
    limitMW,
    resistanceOhm,
    lossMW: roundTo((flowMW * flowMW * resistanceOhm) / 1500, 2),
    status: computeEdgeStatus(flowMW, limitMW),
    isQuantumPath,
    isClassicalPath,
  };
}

